    ('DEPT_EDIT', 'Edit Department', 'Edit a department record', 'Human Resources'),
    ('DEPT_DELETE', 'Delete Department', 'Delete a department record', 'Human Resources'),
    ('EMP_ADD', 'Add Employee', 'Add an employee record', 'Human Resources'),
