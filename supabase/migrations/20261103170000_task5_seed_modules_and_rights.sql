-- 5. Enable RLS on the new tables.
ALTER TABLE public.right_catalogue ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_right ENABLE ROW LEVEL SECURITY;

-- 6. Keep new tables backend-only.
REVOKE ALL ON TABLE public.right_catalogue, public.user_right
    FROM PUBLIC, anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE
    ON TABLE public.right_catalogue, public.user_right
    TO service_role;

-- Grant service_role access to the generated identity sequences.
DO $$
DECLARE
    seq_name text;
BEGIN
    seq_name := pg_get_serial_sequence('public.right_catalogue', 'id');
    IF seq_name IS NOT NULL THEN
        EXECUTE format(
            'REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, authenticated',
            seq_name
        );
        EXECUTE format(
            'GRANT USAGE, SELECT ON SEQUENCE %s TO service_role',
            seq_name
        );
    END IF;

    seq_name := pg_get_serial_sequence('public.user_right', 'id');
    IF seq_name IS NOT NULL THEN
        EXECUTE format(
            'REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, authenticated',
            seq_name
        );
        EXECUTE format(
            'GRANT USAGE, SELECT ON SEQUENCE %s TO service_role',
            seq_name
        );
    END IF;
END $$;

COMMIT;
