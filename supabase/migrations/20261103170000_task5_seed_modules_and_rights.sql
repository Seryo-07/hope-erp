-- S1-DBA-05: Seed Modules and Individual Rights
-- Additive migration: preserves all existing tables and records.

BEGIN;

-- 1. Create individual rights catalogue.
CREATE TABLE IF NOT EXISTS public.right_catalogue (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    right_code text NOT NULL UNIQUE,
    name text NOT NULL,
    description text,
    module_id integer NOT NULL
        REFERENCES public.module(id) ON DELETE RESTRICT,
    status text NOT NULL DEFAULT 'Active',
    is_deleted boolean NOT NULL DEFAULT false,
    stamp text NOT NULL DEFAULT 'CREATED system'
);

-- 2. Create individual user-right assignments.
CREATE TABLE IF NOT EXISTS public.user_right (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL
        REFERENCES public.app_user(id) ON DELETE RESTRICT,
    right_id integer NOT NULL
        REFERENCES public.right_catalogue(id) ON DELETE RESTRICT,
    status text NOT NULL DEFAULT 'Active',
    is_deleted boolean NOT NULL DEFAULT false,
    stamp text NOT NULL DEFAULT 'CREATED system'
);

-- Prevent duplicate active assignments while allowing soft-deleted history.
CREATE UNIQUE INDEX IF NOT EXISTS uq_user_right_active
    ON public.user_right (user_id, right_id)
    WHERE is_deleted = false;

-- 3. Seed the five modules without duplicating existing module names.
INSERT INTO public.module (name, description)
VALUES
    ('Customer', 'Customer management'),
    ('Product', 'Product and price management'),
    ('Human Resources', 'Jobs, departments, employees, and job history'),
    ('Sales', 'Sales transactions and sales details'),
    ('Reports', 'System reports')
ON CONFLICT (name) DO NOTHING;

